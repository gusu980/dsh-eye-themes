#!/usr/bin/env node
/**
 * Build `lib/client.js` (the ModuleLoader bundle the browser runs) and
 * `lib/palettes.json` (the human-auditable token dump) from `src/`.
 *
 * Hand-written bundle, no bundler: the client module system wraps our factory
 * body in a CJS factory and the kernel adopts `{ apply, inject }` as a client
 * plugin. Only `react` is required — it is a shell seed, so no dependency graph
 * row is needed.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PALETTES, TOKEN_NAMES, audit, toOverrideMap } from '../src/palettes.mjs'
import {
  DEFAULT_PAGE_STOP,
  DEFAULT_TEXT_STOP,
  PAGE_STOPS,
  TEXT_STOPS,
  measure,
} from '../src/tune.mjs'

/** The contrast figures that matter to a reader of the dump. */
const pickMeasured = (measured) => ({
  light: { base: measured.light.base, primary: round(measured.light.primary), secondary: round(measured.light.secondary) },
  dark: { base: measured.dark.base, primary: round(measured.dark.primary), primaryHex: measured.dark.primaryHex, secondary: round(measured.dark.secondary) },
})
const round = (value) => Math.round(value * 100) / 100

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

const payload = PALETTES.map((palette) => ({
  id: palette.id,
  name: palette.name,
  tagline: palette.tagline,
  textWarmth: palette.textWarmth,
  tokens: toOverrideMap(palette),
}))

// Every palette must cover every token name, with both modes present.
for (const palette of payload) {
  const missing = TOKEN_NAMES.filter((name) => {
    const pair = palette.tokens[name]
    return pair === undefined || typeof pair.light !== 'string' || typeof pair.dark !== 'string'
  })
  if (missing.length > 0) throw new Error(`${palette.id}: missing tokens ${missing.join(', ')}`)
}

/**
 * Flatten an ESM source file into bare declarations the factory body can use: a
 * hand-written bundle with no bundler cannot import, and the two knobs are
 * applied at runtime, so the colour maths has to travel with the client.
 * @param file - path under src/.
 * @returns the module source without its import/export syntax.
 */
const inlineModule = (file) =>
  readFileSync(join(root, file), 'utf8')
    .replace(/^import[^\n]*\n/gm, '')
    .replace(/^export /gm, '')
    .trim()

const body = readFileSync(join(root, 'src/client.mjs'), 'utf8')
  .replace('__PAYLOAD__', () => JSON.stringify(payload))
  .replace('__ROW_CSS__', () => JSON.stringify(readFileSync(join(root, 'src/row.css'), 'utf8').trim()))

for (const marker of ['__PAYLOAD__', '__ROW_CSS__']) {
  if (body.includes(marker)) throw new Error(`build: marker ${marker} survived — check src/client.mjs`)
}

const runtime = `${inlineModule('src/color.mjs')}\n\n${inlineModule('src/tune.mjs')}`

const bundle = `// GENERATED by tools/build.mjs from src/ — do not edit.
// ${pkg.name} ${pkg.version}: ${PALETTES.length} eye-care palettes for DeepSeek Harness.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' })
${runtime.replace(/^(?=.)/gm, '    ').trimEnd()}

${body.replace(/^(?=.)/gm, '    ').trimEnd()}
    return module.exports
  },
})
`

mkdirSync(join(root, 'lib'), { recursive: true })
writeFileSync(join(root, 'lib/client.js'), bundle)

writeFileSync(
  join(root, 'lib/palettes.json'),
  `${JSON.stringify(
    {
      generated: 'tools/build.mjs',
      tokenCount: TOKEN_NAMES.length,
      pageStops: PAGE_STOPS,
      textStops: TEXT_STOPS,
      defaults: { page: DEFAULT_PAGE_STOP, text: DEFAULT_TEXT_STOP },
      palettes: payload.map((palette, index) => {
        const record = PALETTES[index]
        // Sample table for the README / preview: text stops at the default page brightness.
        const samples = TEXT_STOPS.map((stop) => ({
          stop: stop.id,
          ...pickMeasured(measure(palette.tokens, record, { text: stop.id })),
        }))
        return { ...palette, audit: audit(record), samples }
      }),
    },
    null,
    2,
  )}\n`,
)

const bytes = Buffer.byteLength(bundle)
console.log(
  `built lib/client.js (${(bytes / 1024).toFixed(1)} KiB), lib/palettes.json (${PALETTES.length} palettes x ${TOKEN_NAMES.length} tokens, ${PAGE_STOPS.length} brightness x ${TEXT_STOPS.length} text stops)`,
)
