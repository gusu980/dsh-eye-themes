#!/usr/bin/env node
/**
 * Build `lib/client.js` (the ModuleLoader bundle the browser runs) and
 * `lib/palettes.json` (the human-auditable token dump) from `src/`.
 *
 * Hand-written bundle, no bundler: the client module system wraps our factory
 * body in a CJS factory and the kernel adopts `{ apply, inject }` as a client
 * plugin. Only `react` is required — it is a shell seed, so no dependency graph
 * row is needed.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  ACCENT_TEXT_TOKENS,
  DEFAULT_TEXT_PROFILE,
  LABEL_RAMP_TOKENS,
  ON_FILL_TEXT_TOKENS,
  PALETTES,
  TEXT_PROFILES,
  TOKEN_NAMES,
  audit,
  textAudit,
  toOverrideMap,
  toTextOverrideMaps,
} from '../src/palettes.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

const TEXT_TOKENS = [...LABEL_RAMP_TOKENS, ...ACCENT_TEXT_TOKENS, ...ON_FILL_TEXT_TOKENS]

const payload = PALETTES.map((palette) => ({
  id: palette.id,
  name: palette.name,
  tagline: palette.tagline,
  tokens: toOverrideMap(palette),
  text: toTextOverrideMaps(palette),
}))

// Every palette must carry every text profile, covering the whole copy surface.
for (const palette of payload) {
  for (const profile of TEXT_PROFILES) {
    const map = palette.text[profile.id]
    if (map === undefined) throw new Error(`${palette.id}: missing text profile ${profile.id}`)
    const missing = TEXT_TOKENS.filter((name) => {
      const pair = map[name]
      return pair === undefined || typeof pair.light !== 'string' || typeof pair.dark !== 'string'
    })
    if (missing.length > 0) throw new Error(`${palette.id}/${profile.id}: missing text tokens ${missing.join(', ')}`)
  }
}

// Every palette must cover every token name, with both modes present.
for (const palette of payload) {
  const missing = TOKEN_NAMES.filter((name) => {
    const pair = palette.tokens[name]
    return pair === undefined || typeof pair.light !== 'string' || typeof pair.dark !== 'string'
  })
  if (missing.length > 0) throw new Error(`${palette.id}: missing tokens ${missing.join(', ')}`)
}

const body = readFileSync(join(root, 'src/client.mjs'), 'utf8')
  .replace('__PAYLOAD__', () => JSON.stringify(payload))
  .replace('__TEXT_PROFILES__', () => JSON.stringify(TEXT_PROFILES.map(({ id, label }) => ({ id, label }))))
  .replace('__DEFAULT_TEXT_PROFILE__', () => JSON.stringify(DEFAULT_TEXT_PROFILE))
  .replace('__ROW_CSS__', () => JSON.stringify(readFileSync(join(root, 'src/row.css'), 'utf8').trim()))

for (const marker of ['__PAYLOAD__', '__TEXT_PROFILES__', '__DEFAULT_TEXT_PROFILE__', '__ROW_CSS__']) {
  if (body.includes(marker)) throw new Error(`build: marker ${marker} survived — check src/client.mjs`)
}

const bundle = `// GENERATED by tools/build.mjs from src/ — do not edit.
// ${pkg.name} ${pkg.version}: ${PALETTES.length} eye-care palettes for DeepSeek Harness.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' })
${body.replace(/^(?=.)/gm, '    ').trimEnd()}
    return module.exports
  },
})
`

mkdirSync(join(root, 'lib'), { recursive: true })
writeFileSync(join(root, 'lib/client.js'), bundle)

writeFileSync(
  join(root, 'lib/palettes.json'),
  `${JSON.stringify(
    {
      generated: 'tools/build.mjs',
      tokenCount: TOKEN_NAMES.length,
      textProfiles: TEXT_PROFILES.map(({ id, label, ceiling, warmth }) => ({ id, label, ceiling, warmth })),
      defaultTextProfile: DEFAULT_TEXT_PROFILE,
      palettes: payload.map((palette, index) => ({
        ...palette,
        audit: audit(PALETTES[index]),
        textAudit: textAudit(PALETTES[index]),
      })),
    },
    null,
    2,
  )}\n`,
)

const bytes = Buffer.byteLength(bundle)
console.log(
  `built lib/client.js (${(bytes / 1024).toFixed(1)} KiB), lib/palettes.json (${PALETTES.length} palettes x ${TOKEN_NAMES.length} tokens, ${TEXT_PROFILES.length} text temperatures)`,
)
